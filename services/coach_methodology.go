// 追问是「就着一个具体问题给个短答案」，把六千字方法论全带上会让模型倾向
// 输出长篇大论，与追问 300 字以内的要求冲突。这里只留最影响单点判断的部分：
// 形象五格、行动优先级、尺度与赔率的硬数字。
const coachMethodologyBrief = `
# 教练打法方法论要点（《小绿皮书》）

回答时必须与下面这些原则一致，不要给放之四海皆准的通用道理。

**五格形象与对策**：松弱（跟注站）→永不诈唬永不慢打、纯价值下注；
紧弱（岩石）→打松偷他、他终于下注就弃；松凶（LAG）→别对攻、持强牌过牌-跟注让他自毁、
注意他做小池时反而有强牌；紧凶（TAG）→避开、减少诈唬、他翻后跟注往往在慢打；
**未知（样本不足 3 次）→ 按标准线打，不做剥削性偏离**。

**行动优先级**：先问能不能下注或加注，再问要不要过牌或弃牌。
下注和加注是默认方，过牌和弃牌需要理由——说不出理由的过牌与说不出理由的下注同样是漏损。
建议过牌只允许这几种理由：多人池且完全没牌 / 转牌出吓人牌让出开火权 /
中三条且对手弱 / 坚果花或葫芦慢打 / 河牌中等牌引诱诈唬 / 对手是过牌-加注型。

**范围推断的四条线索**：位置（越靠后越宽）/ 下注尺度（小=想被跟，大=想弃牌，
且必须先确认这个对手是哪种类型）/ 过牌（区分示弱、陷阱、听牌三种）/
加注（**一个人没做的动作和做了的动作一样有信息量**）。
不许把范围说成确定的牌；样本不足 3 次不谈范围。

**尺度与赔率**：持续下注按单挑情形取值（65%/85%/50%/75-80%/65%），不要给笼统频率；
下注尺度用四因素法（牌对上对手范围的强度 / 我的牌变强的概率 / 对手中牌的概率 /
对手有优质抽牌的概率），四者不同取平均。
赔率：1/3 池需 20% 胜率、1/2 池 25%、1 倍池 33%、2 倍池 40%；
对手转牌下注达到或超过 1/2 池时，用 9 张 outs 及以下的听牌跟注都是错误
（组合听牌是例外：12 张 outs 单街约 26%、15 张约 33%，都已高于门槛）。
`
